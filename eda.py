def plot_box(df, feature, ax, target = 'target', **kwargs):
    '''
    Plots a box plot.
    df: Dataframe
    feature: str of feature
    ax: Matplotlib axes object
    '''

    sns.boxplot(x = target, y = feature, data = df, ax = ax, **kwargs)
    ax.set_title(feature)

"""### Violin plot"""

def plot_violin(df, feature, ax, target = 'target', **kwargs):
    '''
    Plots a violin plot.
    df: Dataframe
    feature: str of feature
    ax: Matplotlib axes object
    target: str of target
    '''

    sns.violinplot(x=target, y = feature, data = df, ax = ax, inner = 'quartile', **kwargs)
    ax.set_title(feature)

"""### Histogram"""

def plot_hist(df, feature, ax, target = None):
    '''
    Plots a histogram and calculates the skewness of the feature.
    df: DataFrame
    feature: str of feature
    ax: Matplotlib axes object
    '''

    sns.histplot(df[feature], ax = ax)
    ax.set_title(feature)
    skew_val = df[feature].skew()
    ax.text(0.9, 0.85, f'Skew: {skew_val:.2f}', transform = ax.transAxes,
            ha = 'right', fontsize = 11, weight = 'bold')

"""### Box-Tidwell / Linearity check"""

def plot_linearity(df, feature, ax, target = 'target', num_bins = 10):
    '''
    Plots a scatter plot and checks for linearity with Box-Tidwell test.
    df: Dataframe
    feature: str of feature
    ax: Matplotlib axes object
    target: str of target
    num_bins: int of number of bins
    '''

    if feature == target:
        ax.set_visible(False)
        return None
    try:
        X_bt = df[[feature]] + 1e-6
        X_bt[f'{feature}_logX'] = X_bt[feature] * np.log(X_bt[feature])
        X_bt = sm.add_constant(X_bt)
        model_bt = sm.Logit(df[target].astype(int), X_bt).fit(disp=0)
        bt_pval = model_bt.pvalues[f'{feature}_logX']
    except Exception as e:
        print(f'Skipping Box-Tidwell for {feature}: {e}')
        bt_pval = np.nan

    bins = pd.cut(df[feature], bins=num_bins)
    binned_props = df.groupby(bins, observed=False)[target].mean()
    probs = np.clip(binned_props.values, 0.001, 0.999)
    log_odds = np.log(probs / (1 - probs))
    bin_midpoints = [interval.mid for interval in binned_props.index]

    sns.scatterplot(x = bin_midpoints, y = log_odds, ax = ax)
    sns.regplot(x = bin_midpoints, y = log_odds, scatter = False, ax = ax,
                color = 'red', line_kws = {'linestyle':'--'})
    ax.set_title(f'{feature} (BT p = {bt_pval:.4f})')

    return bt_pval

"""### Count Plot"""

def plot_target_distribution(y, **kwargs):
    '''
    Plot the count of the target variable as a categorical variable.
    y: Series of target values (numeric or categorical)
    '''

    # Convert numeric targets to string categories for plotting
    if np.issubdtype(y.dtype, np.number):
        y_plot = y.map(lambda x: f'Class {int(x)}')
    else:
        y_plot = y

    sns.countplot(x = y_plot)
    plt.title('Target Distribution')
    plt.show()

"""### Correlation Clustermap"""

def plot_corr_clustermap(corr_data):
    '''
    Plots a correlation clustermap.
    corr_data: 2D array of correlation values
    '''
    cg = sns.clustermap(corr_data, cmap = 'coolwarm', annot = True, figsize = (20, 24))
    cg.fig.suptitle('Correlation Clustermap', y = 1.02)
    plt.show()