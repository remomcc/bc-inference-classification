import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import statsmodels.api as sm

"""## General grid function"""

def plot_feature_grid(df, plot_func, cols = 4, figsize_per_row = (16, 3),
                      suptitle = None, target = 'target', map_target=True, **kwargs):
    '''
    Plots all features in a grid using the given plot function.
    Collects returned values from each plot_func.
    df: DataFrame
    plot_func: function to plot each feature
    cols: number of columns in the grid
    figsize_per_row: tuple of (width, height) for each row
    suptitle: title for the figure
    target: str of target
    '''

    df_copy = df.copy()
    features = [col for col in df_copy.columns if col != target]
    n_features = len(features)
    rows = int(np.ceil(n_features / cols))

    fig, axes = plt.subplots(rows, cols, figsize = (figsize_per_row[0], rows * figsize_per_row[1]))
    axes = axes.ravel() if n_features > 1 else [axes]

    results = {}

    # Determine if target should be categorical
    is_target_categorical = df_copy[target].dtype in [np.int64, np.float64] and plot_func.__name__ in ['plot_box', 'plot_violin']

    if is_target_categorical:
        # convert to string categories temporarily
        df_copy[target] = df_copy[target].map(lambda x: f'Class {int(x)}')

    for idx, feature in enumerate(features):
        ret = plot_func(df_copy, feature, axes[idx], target = target, **kwargs)
        if ret is not None:
            results[feature] = ret

    # Hide unused axes
    for ax in axes[n_features:]:
        ax.set_visible(False)

    if suptitle:
        plt.suptitle(suptitle, fontsize = 16, y = 1.02)
        fig.tight_layout(rect = [0, 0, 1, 0.95])
    else:
        fig.tight_layout()

    plt.show()

    return pd.DataFrame.from_dict(results, orient='index', columns=['Value']) if results else None

