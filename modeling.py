class PipelineBuilder:
    '''
    Build sklearn Pipeline per model according to model_intent.

    For classification, the preprocessing steps (transform / scale / vif)
    are embedded inside a standard sklearn Pipeline so that
    RandomizedSearchCV can clone and refit them.

    Each pipeline has the structure:
        [('transform', SafeTransformer), ('scaler', DataFrameScaler),
         ('vif', VIFSelector), ('model', estimator)]
    where steps are omitted if the corresponding intent flag is False.
    '''

    def __init__(self, models, model_intent, feature_transforms = None,
                 vif_thresh = 5.0):
        '''
        models: dict {model name: estimator}
        model_intent: dict {model name: {'transform': bool, 'scale': bool, 'vif': bool}}
        feature_transforms: dict or None which is forwarded to SafeTransformer.
        vif_thresh: float VIF threshold used in VIFSelector.
        '''

        self.models = models
        self.model_intent = model_intent or {}
        self.feature_transforms = feature_transforms
        self.vif_thresh = vif_thresh

    def build(self):
        '''
        Build model pipeline.
        '''

        pipelines = {}

        for name, model in self.models.items():
            intent = self.model_intent.get(name) or {}

            steps = []
            if intent.get('transform', False):
                steps.append(('transform', SafeTransformer(self.feature_transforms)))
            if intent.get('scale', False):
                steps.append(('scaler', DataFrameScaler()))
            if intent.get('vif', False):
                steps.append(('vif', VIFSelector(thresh=self.vif_thresh)))

            steps.append(('model', model))
            pipelines[name] = Pipeline(steps)

        return pipelines

class ModelTrainer:
    '''
    Fit pipelines, optionally running RandomizedSearchCV for hyperparameter
    tuning where a param_grid is specified.
    '''

    def __init__(self, param_grids = None, cv = None, scoring = 'roc_auc',  n_iter = 20):
        '''
        param_grids: dict of model parameters {model name: {parameter name: parameter,...}}
        cv: sklearn CV splitter
        n_iter: int number for RandomizedSearchCV iterations
        scoring: str for scoring metric of RandomizedSearchCV
        '''

        self.param_grids = param_grids or {}
        self.cv = cv
        self.n_iter = n_iter
        self.scoring = scoring

    def fit(self, pipelines, X, y):
        '''
        Return dict best fitted pipeline {name: best_pipeline}
        '''

        # Best pipeline dictionary
        best = {}

        # Find best hyperparameters per model
        for name, pipe in pipelines.items():

            # Run RandomizedSearchCV if param_grid provided
            if name in self.param_grids:
                search = RandomizedSearchCV(
                    pipe, self.param_grids[name],
                    n_iter = self.n_iter, cv = self.cv,
                    scoring = self.scoring, n_jobs = -1, random_state = 42
                )
                search.fit(X, y)
                best[name] = search.best_estimator_
            else:
                pipe.fit(X, y)
                best[name] = pipe

        return best

class CrossValidator:
    '''
    Run stratified k-fold CV, compute PR-AUC per fold, and find the
    threshold that maximises F2 score using a coarse-to-fine grid search.
    '''

    def __init__(self, cv, coarse_n=50, fine_n=50, zoom_frac=0.1):
        '''
        cv: sklearn CV splitter
        coarse_n, fine_n: int number for grid points in threshold search
        zoom_frac: float half-width around for fine search threshold
        '''

        self.cv = cv
        self.coarse_n = coarse_n
        self.fine_n = fine_n
        self.zoom_frac = zoom_frac

    def evaluate(self, pipelines, X, y):
        '''
        Run cross-validation
        pipelines: dict {model name: Pipeline}
        X: DataFrame of features
        y: series of target labels
        '''

        threshold_info = {}
        rows = []

        for name, pipe in pipelines.items():
            all_thresh, pr_aucs = [], []

            for tr_idx, val_idx in self.cv.split(X, y):
                X_tr, X_val = X.iloc[tr_idx], X.iloc[val_idx]
                y_tr, y_val = y.iloc[tr_idx], y.iloc[val_idx]

                cv_pipe = clone(pipe)
                cv_pipe.fit(X_tr, y_tr)
                y_prob, _, _ = get_probabilities(cv_pipe, X_val)
                pr_aucs.append(average_precision_score(y_val, y_prob))

                # Coarse search
                coarse = np.linspace(0, 1, self.coarse_n)
                f2_c = [fbeta_score(y_val, (y_prob >= t).astype(int), beta=2) for t in coarse]
                best_c = coarse[np.argmax(f2_c)]

                # Fine search
                fine = np.linspace(max(0, best_c - self.zoom_frac / 2),
                                   min(1, best_c + self.zoom_frac / 2),
                                   self.fine_n)
                f2_f = [fbeta_score(y_val, (y_prob >= t).astype(int), beta=2) for t in fine]

                # Append best threshold
                all_thresh.append(fine[np.argmax(f2_f)])

            threshold_info[name] = float(np.mean(all_thresh))
            rows.append({
                'model': name,
                'cv_pr_auc': float(np.mean(pr_aucs)),
                'cv_pr_auc_std': float(np.std(pr_aucs)),
            })

        return pd.DataFrame(rows), threshold_info

class ModelAnalyzer:
    '''
    Evaluate pipelines on the hold-out test set, build feature tables,
    and perform error analysis on the best model.
    '''

    def __init__(self, X_train, y_train, X_test, y_test,
                 best_pipelines, threshold_info, cv_results):
        '''
        X_train: Dataframe of training data
        y_train: series of training labels
        X_test: Dataframe of testing data
        y_test: series of testing labels
        best_pipelines: dict of trained pipelines per model {model_name: Pipeline}
        threshold_info: dict of optimal thresholds from CV {model_name: float}
        cv_results: DataFrame of cross-validation results per model.
        '''

        self.X_train, self.y_train = X_train, y_train
        self.X_test, self.y_test = X_test, y_test
        self.best_pipelines = best_pipelines
        self.threshold_info = threshold_info
        self.cv_results = cv_results

        # Populated by evaluate_test_set()
        self.test_df = None
        self.results_df = None
        self.best_model_name = None
        self.best_model_pipeline = None
        self.best_threshold = None

        # Populated by build_feature_processing_table()
        self.feature_processing_table_ = None

        # Populated by analyze_errors()
        self.error_analysis = None

    # --- Test-set evaluation --------------------------------------------------
    def _compute_metrics(self, y_true, y_pred, y_prob, y_prob_matrix, threshold):
        '''
        Return dictionary of computed metrics from
        y_true: series of actual labels
        y_pred: series of predicted labels
        y_prob: series of predicted probabilities
        y_prob_matrix: array of predicted probabilities
        threshold: float for model threshold
        '''

        return {
            'threshold': threshold,
            'accuracy': accuracy_score(y_true, y_pred),
            'precision': precision_score(y_true, y_pred, pos_label=1, zero_division=0),
            'recall': recall_score(y_true, y_pred, pos_label=1),
            'f1': f1_score(y_true, y_pred, pos_label=1, zero_division=0),
            'f2': fbeta_score(y_true, y_pred, beta=2, average='binary'),
            'pr_auc': average_precision_score(y_true, y_prob),
            'roc_auc': roc_auc_score(y_true, y_prob),
            'brier_score': brier_score_loss(y_true, y_prob, pos_label=1),
            'log_loss': log_loss(y_true, y_prob_matrix),
            'ece': compute_ece(y_true.values, y_prob),
        }

    def evaluate_test_set(self):
        '''
        Compute metrics for all pipelines and identify the best model.
        '''

        # Each row is for each model and its computed metrics (separate columns)
        rows = []
        for name, pipe in self.best_pipelines.items():
            y_prob, _, y_prob_matrix = get_probabilities(pipe, self.X_test)
            threshold = self.threshold_info[name]
            y_pred = (y_prob >= threshold).astype(int)
            metrics = self._compute_metrics(self.y_test, y_pred, y_prob, y_prob_matrix, threshold)
            rows.append({'model': name, **metrics})

        # Convert row metrics into dataframe with CV results
          # Prioritize F2 score
        self.test_df = pd.DataFrame(rows)
        self.results_df = (
            self.test_df
            .merge(self.cv_results, on = 'model', how = 'left')
            .sort_values(['f2', 'recall', 'brier_score'], ascending=[False, False, True])
            .reset_index(drop=True)
        )

        # Best model metrics
        best_row = self.results_df.iloc[0]
        self.best_model_name = best_row['model']
        self.best_model_pipeline = self.best_pipelines[self.best_model_name]
        self.best_threshold = self.threshold_info[self.best_model_name]

        return self.results_df

    # --- Feature table builder ------------------------------------------------
    def build_feature_processing_table(self):
        '''
        Summarize transformations, scaling, VIF, and importance of each feature in each model.
        '''

        rows = []

        for name, pipeline in self.best_pipelines.items():
            model       = pipeline.named_steps['model']
            transformer = pipeline.named_steps.get('transform')
            scaler      = pipeline.named_steps.get('scaler')
            vif_step    = pipeline.named_steps.get('vif')

            all_features = list(self.X_train.columns)
            feature_metadata = {f: {} for f in all_features}

            # Transform metadata
            if transformer and hasattr(transformer, 'get_feature_metadata'):
                for f, meta in transformer.get_feature_metadata().items():
                    feature_metadata[f].update(meta if isinstance(meta, dict) else {'transformation': meta})
            else:
                for f in all_features:
                    feature_metadata[f]['transformation'] = 'raw'

            # Scaling
            for f in all_features:
                feature_metadata[f]['scaled'] = bool(scaler)

            # VIF selection
            if vif_step and hasattr(vif_step, 'selected_features_'):
                selected = set(vif_step.selected_features_)
                final_features = list(vif_step.selected_features_)
                for f in all_features:
                    feature_metadata[f]['dropped_by_vif'] = f not in selected
            else:
                final_features = all_features
                for f in all_features:
                    feature_metadata[f]['dropped_by_vif'] = False

            # Importance
            coef_map, imp_map, perm_map = {}, {}, {}

            # Coefficients
            if hasattr(model, 'coef_'):
                coef_map = dict(zip(final_features, model.coef_.ravel()))

            # Tree-based importance
            if hasattr(model, 'feature_importances_'):
                imp_map = dict(zip(final_features, model.feature_importances_))

            # Permutation importance (ALWAYS compute)
            try:
                r = permutation_importance(
                    pipeline,
                    self.X_test,
                    self.y_test,
                    n_repeats=10,
                    random_state=42,
                    n_jobs=-1
                )
                perm_map = dict(zip(all_features, r.importances_mean))
            except Exception:
                perm_map = {}

            for f in all_features:
                dropped = feature_metadata[f].get('dropped_by_vif', False)

                row = {
                    'model': name,
                    'feature': f,
                    'transformation': feature_metadata[f].get('transformation', 'raw'),
                    'scaled': feature_metadata[f].get('scaled', False),
                    'dropped_by_vif': dropped,

                    # Linear models
                    'coefficient': coef_map.get(f, np.nan),

                    # Tree-based models
                    'importance': imp_map.get(f, np.nan),

                    # Model-agnostic (only if not dropped by VIF)
                    'permutation_importance': (
                        perm_map.get(f, np.nan) if not dropped else np.nan
                    )
                }

                rows.append(row)

            if hasattr(model, 'intercept_'):
                rows.append({
                    'model': name,
                    'feature': '__intercept__',
                    'transformation': None,
                    'scaled': None,
                    'dropped_by_vif': False,
                    'coefficient': float(np.ravel(model.intercept_)[0]),
                    'importance': np.nan,
                    'permutation_importance': np.nan
                })

        self.feature_processing_table_ = pd.DataFrame(rows)
        return self.feature_processing_table_

    def get_final_features(self, model_name):
        '''
        Return list of final features for model.
        model_name: str name of model
        '''

        if self.feature_processing_table_ is None:
            raise RuntimeError('Call build_feature_processing_table() first.')
        df = self.feature_processing_table_.query(
            'model == @model_name and not dropped_by_vif and feature != "__intercept__"'
        )
        return df['feature'].tolist()

    # --- Error analysis -------------------------------------------------------
    def _detect_outliers(self, X, z_thresh = 3.0, iqr_factor = 1.5):
        '''
        Detect outliers.
        X: DataFrame of features
        z_thresh: float for z-score threshold
        iqr_factor: float for IQR threshold
        '''

        # Boolean mask to retrieve if any of the sample's feature values are outside of z-score threshold.
        z_out = (np.abs(zscore(X)) > z_thresh).any(axis=1)

        # Outside of interquartile range
        Q1, Q3 = X.quantile(0.25), X.quantile(0.75)
        IQR = Q3 - Q1
        iqr_out = ((X < Q1 - iqr_factor * IQR) | (X > Q3 + iqr_factor * IQR)).any(axis=1)

        return z_out, iqr_out

    def analyze_errors(self, z_thresh = 3.0, iqr_factor = 1.5, top_n = 10):
        '''
        Build error analysis for the best model.
        z_thresh: float for z-score threshold
        iqr_factor: float for IQR threshold
        top_n: int for # of most confident errors
        '''

        # Extract best model
        pipe = self.best_model_pipeline
        threshold = self.best_threshold
        y_proba, _, _ = get_probabilities(pipe, self.X_test)
        y_pred = (y_proba >= threshold).astype(int)

        df = self.X_test.copy()
        df['y_true'] = self.y_test.values
        df['y_pred'] = y_pred
        df['y_proba'] = y_proba
        df['is_error'] = df['y_true'] != df['y_pred']

        # Determine feature outlier values
        feats = df.drop(columns=['y_true', 'y_pred', 'y_proba', 'is_error'])
        df['zscore_outlier'], df['iqr_outlier'] = self._detect_outliers(feats, z_thresh, iqr_factor)

        confident = (
            df.loc[df['is_error']]
            .assign(confidence = lambda d: np.where(d['y_pred'] == 1, d['y_proba'], 1 - d['y_proba']))
            .sort_values('confidence', ascending = False)
            .head(top_n)
        )

        self.error_analysis = {
            'full_table': df,
            'false_positives': df[(df.y_true == 0) & (df.y_pred == 1)],
            'false_negatives': df[(df.y_true == 1) & (df.y_pred == 0)],
            'confident_errors': confident,
            'summary': (
                df.groupby('is_error')[['zscore_outlier', 'iqr_outlier']]
                .mean()
                .rename(index={False: 'Correct', True: 'Incorrect'})
            )
        }
        return self.error_analysis

    def _rebuild_error_analysis(self, df, top_n=10):
        '''
        Reconstruct error_analysis dict from saved full_table csv.
        df: DataFrame with errors
        top_n: int for # of most confident errors
        '''

        confident = (
            df.loc[df['is_error']]
            .assign(confidence=lambda d: np.where(
                d['y_pred'] == 1, d['y_proba'], 1 - d['y_proba']
            ))
            .sort_values('confidence', ascending=False)
            .head(top_n)
        )

        self.error_analysis = {
            'full_table': df,
            'false_positives': df[(df.y_true == 0) & (df.y_pred == 1)],
            'false_negatives': df[(df.y_true == 1) & (df.y_pred == 0)],
            'confident_errors': confident,
            'summary': (
                df.groupby('is_error')[['zscore_outlier', 'iqr_outlier']]
                .mean()
                .rename(index={False: 'Correct', True: 'Incorrect'})
            )
        }

        return self.error_analysis

class ModelEvaluator:
    '''
    Orchestrator for training, CV, and analysis.
    '''

    def __init__(self, X_train, y_train, X_test, y_test, cv,
                 models, param_grids, model_intent, scoring = 'roc_auc',
                 feature_transforms = None,
                 coarse_n = 50, fine_n = 50, zoom_frac = 0.1,
                 error_top_n = 10,
                 output_dir = Path('model_eval')):
        '''
        X_train: Dataframe of training data
        y_train: series of training labels
        X_test: Dataframe of testing data
        y_test: series of testing labels
        cv: sklearn CV splitter
        models: dict of models
        param_grids: dict of param grids per model
        model_intent: dict of model intent
        feature_transforms: dict of feature transformations
        coarse_n: float for coarse grid search
        fine_n: float for fine grid search
        zoom_frac: float half-width around for fine search threshold
        error_top_n: int # of most confident errors
        output_dir: file path for output
        '''

        self.X_train, self.y_train = X_train, y_train
        self.X_test,  self.y_test  = X_test, y_test
        self.cv = cv
        self.models = models
        self.param_grids = param_grids
        self.model_intent = model_intent
        self.scoring = scoring
        self.feature_transforms = feature_transforms
        self.error_top_n = error_top_n

        self.builder = PipelineBuilder(models, model_intent, feature_transforms)
        self.cv_runner = CrossValidator(cv, coarse_n, fine_n, zoom_frac)

        # In-memory state
        self.best_pipelines = {}
        self.cv_results = None
        self.threshold_info = {}
        self.analyzer = None

        # Disk layout
        self.output_dir = Path(output_dir)
        self.pipeline_dir = self.output_dir / 'pipelines'
        self.cv_file = self.output_dir / 'cv_results.pkl'
        self.thresh_file = self.output_dir / 'thresholds.pkl'
        self.feat_file = self.output_dir / 'feature_table.csv'
        self.error_file = self.output_dir / 'error_analysis.csv'

        for d in [self.output_dir, self.pipeline_dir]:
            d.mkdir(parents=True, exist_ok=True)

        self._load_existing()

    # --- Disk I/O -------------------------------------------------------------
    def _load_existing(self):
        '''
        Load pipelines, CV, thresholds, and reconstruct analyzer if they already exist.
        '''

        for name in self.models:
            p = self.pipeline_dir / f'{name}.pkl'
            if p.exists():
                with open(p, 'rb') as f:
                    self.best_pipelines[name] = pickle.load(f)

        if self.cv_file.exists():
            with open(self.cv_file, 'rb') as f:
                self.cv_results = pickle.load(f)

        if self.thresh_file.exists():
            with open(self.thresh_file, 'rb') as f:
                self.threshold_info = pickle.load(f)

        # Only reconstruct analyzer if pipelines + thresholds exist
        if self.best_pipelines and self.threshold_info:
            self.analyzer = ModelAnalyzer(
                self.X_train, self.y_train,
                self.X_test, self.y_test,
                self.best_pipelines,
                self.threshold_info,
                self.cv_results
            )

            # Load analysis CSVs into analyzer
            if self.feat_file.exists():
                self.analyzer.feature_processing_table_ = pd.read_csv(self.feat_file)

            if self.error_file.exists():
                df = pd.read_csv(self.error_file)
                if not df.empty:
                    self.analyzer.error_analysis = self.analyzer._rebuild_error_analysis(df, top_n = self.error_top_n)

    def _save(self, obj, path, mode='pkl'):
        '''
        Save obj to path.
        obj: object to save
        path: file path
        '''

        path = Path(path)
        if mode == 'pkl':
            with open(path, 'wb') as f:
                pickle.dump(obj, f)
        else:
            obj.to_csv(path, index=False)

    # --- Stage completion checks ----------------------------------------------
    def _pipelines_complete(self):
        '''
        Return True if all pipelines have been trained.
        '''
        return all(name in self.best_pipelines for name in self.models)

    def _cv_complete(self):
        '''
        Return True if CV results have been computed.
        '''
        return (self.cv_results is not None and
                bool(self.threshold_info) and
                all(name in self.threshold_info for name in self.models))

    # --- Run / resume ---------------------------------------------------------
    def run(self):
        '''
        Run all stages of the pipeline.
        '''

        # Run the building of the pipeline
        self._run_stage_1_pipelines()

        # Run cross-validation and threshold optimization
        self._run_stage_2_cv()

        # Run error analysis
        self._run_stage_3_analyze()

        return self.analyzer

    def resume(self):
        '''
        Resume the pipeline.
        '''
        return self.run()

    # --- Stages ---------------------------------------------------------------
    def _run_stage_1_pipelines(self):
        '''
        Run the building of the pipeline.
        '''

        # Check if pipelines have been completed
        if self._pipelines_complete():
            return

        # Build pipelines if they are not missing
        missing = [n for n in self.models if n not in self.best_pipelines]
        models_subset = {n: self.models[n] for n in missing}
        intent_subset = {n: self.model_intent.get(n, {}) for n in missing}
        param_subset = {n: self.param_grids.get(n) for n in missing if n in self.param_grids}

        partial_builder = PipelineBuilder(models_subset, intent_subset, self.feature_transforms)
        pipelines = partial_builder.build()

        # Hyperparameter tuning with RandomizedGridSearch and param subset
        trainer = ModelTrainer(param_subset, self.cv, self.scoring)
        new_pipelines = trainer.fit(pipelines, self.X_train, self.y_train)

        # Save best model with hyperparameters
        for name, pipe in new_pipelines.items():
            self.best_pipelines[name] = pipe
            self._save(pipe, self.pipeline_dir / f'{name}.pkl')

    def _run_stage_2_cv(self):
        '''
        Run cross-validation and threshold optimization.
        '''

        # Check if cross-validation has been completed
        if self._cv_complete():
            return

        # Run cross-validation
        self.cv_results, self.threshold_info = self.cv_runner.evaluate(
            self.best_pipelines, self.X_train, self.y_train
        )

        # Save CV results and threshold information per model
        self._save(self.cv_results, self.cv_file)
        self._save(self.threshold_info, self.thresh_file)

    def _run_stage_3_analyze(self):
        '''
        Run analyzer.
        '''

        if not self.analyzer:
            self.analyzer = ModelAnalyzer(
                self.X_train, self.y_train,
                self.X_test, self.y_test,
                self.best_pipelines,
                self.threshold_info,
                self.cv_results
            )
        self.analyzer.evaluate_test_set()

        # Persist feature table
        if self.analyzer.feature_processing_table_ is None:
            self.analyzer.build_feature_processing_table()
            self._save(self.analyzer.feature_processing_table_, self.feat_file, mode='csv')

        # Persist error analysis
        if self.analyzer.error_analysis is None:
            self.analyzer.analyze_errors()
            self._save(self.analyzer.error_analysis['full_table'], self.error_file, mode='csv')

    def get_final_features(self, model_name):
        '''
        Return list of final features for model.
        model_name: str name of model
        '''

        if self.analyzer is None:
            raise RuntimeError('Call run() first.')

        return self.analyzer.get_final_features(model_name)

    def build_feature_processing_table(self):
        '''
        Build feature processing table.
        '''

        if self.analyzer is None:
            raise RuntimeError('Call run() first.')

        return self.analyzer.build_feature_processing_table()

    def analyze_errors(self):
        '''
        Run error analysis.
        '''

        if self.analyzer is None:
            raise RuntimeError('Call run() first.')

        return self.analyzer.analyze_errors()

class ModelVisualizer:
    '''
    Plot PR/ROC curves, confusion matrices, feature importance, SHAP
    summaries, dependence plots, error distributions, and waterfall charts.
    '''

    def __init__(self, analyzer):
        '''
        analyzer: ModelAnalyzer
        '''
        self.analyzer = analyzer
        self.X_train = analyzer.X_train
        self.y_train = analyzer.y_train
        self.X_test = analyzer.X_test
        self.y_test = analyzer.y_test
        self.test_df = analyzer.test_df
        self.results_df = analyzer.results_df
        self.threshold_info = analyzer.threshold_info
        self.best_pipelines = analyzer.best_pipelines
        self.best_model_pipeline = analyzer.best_model_pipeline
        self.error_analysis = analyzer.error_analysis

    # --- Data Preparation -----------------------------------------------------
    def _transform_features(self, pipeline, X):
        '''
        Apply all preprocessing steps (all steps except 'model').
        pipeline: Pipeline object
        X: DataFrame of features
        '''

        # Tree-based model features do not need feature transformation
        if len(pipeline.steps) <= 1:
            return X

        return pipeline[:-1].transform(X)

    def _get_target_sample(self, name, pipeline, sample_size, random_state,
                           target_sampling):
        '''
        Return target sample (X_transformed_sample, chosen_indices).
        name: str name of model
        pipeline: Pipeline object
        sample_size: int size of sample
        random_state: int seed for random number generator
        target_sampling: str or callable() for type of sample.
              Options: positive, negative, high_error, callable()
        '''

        X_trans = self._transform_features(pipeline, self.X_test)

        cols = self.analyzer.get_final_features(name)

        if X_trans.shape[1] != len(cols):
            # Ensures the DataFrame has correct columns
            X_trans = pd.DataFrame(X_trans, columns=cols, index=self.X_test.index)
        elif not isinstance(X_trans, pd.DataFrame):
            X_trans = pd.DataFrame(X_trans, columns=cols, index=self.X_test.index)

        y_prob, _, _ = get_probabilities(pipeline, self.X_test)

        # Filtering based on target sampling
        if target_sampling == 'positive':
            mask = y_prob >= 0.5
        elif target_sampling == 'negative':
            mask = y_prob < 0.5
        elif target_sampling == 'high_error':
            errors = np.abs(y_prob - self.y_test.values)
            mask   = errors > np.percentile(errors, 75)
        elif callable(target_sampling):
            mask = target_sampling(self.X_test, self.y_test)
        else:
            # Default all rows available
            mask = np.ones(len(X_trans), dtype = bool)

        mask = np.asarray(mask, dtype = bool)
        indices = np.where(mask)[0]
        if len(indices) == 0:
            indices = np.arange(len(X_trans))

        # Randomly selected rows for
        rng = np.random.default_rng(random_state)
        chosen = rng.choice(indices, size = min(sample_size, len(indices)), replace = False)

        return X_trans.iloc[chosen], chosen

    # --- Plots ----------------------------------------------------------------
    def plot_evaluation_metrics(self, name, pipeline):
        '''
        Plot PR curve, ROC curve, and confusion matrix in one row.
        name: str name of model
        pipeline: Pipeline object
        '''

        threshold = self.threshold_info.get(name, 0.5)
        y_prob, _, _ = get_probabilities(pipeline, self.X_test)
        y_pred = (y_prob >= threshold).astype(int)

        fig, axs = plt.subplots(1, 3, figsize=(18, 5))

        prec, rec, _ = precision_recall_curve(self.y_test, y_prob)
        axs[0].plot(rec, prec)
        axs[0].set_title(f'{name} — Precision–Recall')

        RocCurveDisplay.from_predictions(self.y_test, y_prob, ax=axs[1])
        axs[1].set_title(f'{name} — ROC')

        cm = confusion_matrix(self.y_test, y_pred, labels=[1, 0])
        ConfusionMatrixDisplay(cm, display_labels=['Malignant', 'Benign']).plot(
            ax = axs[2], cmap = 'Blues', colorbar = False
        )
        axs[2].set_title(f'{name} — Confusion matrix (thresh={threshold:.2f})')

        plt.tight_layout()
        plt.show()

    # ------------------------------------------------------------------
    def importance_table(self, name, pipeline):
        '''
        Table of important features
        '''

        df = self.analyzer.feature_processing_table_

        # Ensure feature processing table exists
        if df is None:
            df = self.analyzer.build_feature_processing_table()

        df_model = df[(df['model'] == name) & (df['dropped_by_vif'] == False)].copy()

        # Remove intercept
        df_model = df_model[df_model['feature'] != '__intercept__']

        # Drop non-display columns
        df_model = df_model.drop(
            columns=['model', 'scaled', 'dropped_by_vif'],
            errors='ignore'
        )

        # Keep only meaningful importance columns
        importance_cols = ['coefficient', 'importance', 'permutation_importance']
        keep_importance = [
            col for col in importance_cols
            if col in df_model and df_model[col].notna().any()
        ]

        df_model = df_model[['feature', 'transformation'] + keep_importance]

        # Sort by best available metric
        for col in ['permutation_importance', 'importance', 'coefficient']:
            if col in keep_importance:
                df_model = df_model.sort_values(col, key=abs, ascending=False)
                break

        print(f'\n{name} — Important Features\n')
        display(df_model.reset_index(drop=True))

