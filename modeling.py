    def plot_shap_analysis(self, name, sample_size = 100, background_size = 50,
                           random_state = 42, target_sampling = None):
        '''
        SHAP bar + beeswarm plots for the names model.
        name: str name of model
        sample_size: int size of sample
        background_size: int size of background
        random_state: int seed for random number generator
        target_sampling: str or callable() for type of sample.
        '''

        pipeline = self.best_pipelines[name]
        model = pipeline.named_steps['model']
        X_sample, _ = self._get_target_sample(
            name, pipeline, sample_size, random_state, target_sampling)
        feature_names = self.analyzer.get_final_features(name)

        if X_sample.shape[1] != len(feature_names):
            logging.warning(f'Feature mismatch for SHAP ({name}). Skipping.')
            return

        X_train_trans = self._transform_features(pipeline, self.X_train)

        if hasattr(model, 'feature_importances_'):
            explainer = shap.TreeExplainer(model)
            shap_values = explainer.shap_values(X_sample)
            if isinstance(shap_values, list):
                shap_values = shap_values[1]

        elif hasattr(model, 'coef_'):
            explainer = shap.LinearExplainer(model, X_train_trans)
            shap_values = explainer.shap_values(X_sample)

        elif hasattr(model, 'decision_function'):
            bg = shap.kmeans(X_train_trans, background_size)
            explainer = shap.KernelExplainer(model.decision_function, bg)
            shap_values = explainer.shap_values(X_sample, nsamples=200)

        else:
            bg = shap.kmeans(X_train_trans, background_size)
            explainer = shap.KernelExplainer(
                lambda x: model.predict_proba(x)[:, 1], bg)
            shap_values = explainer.shap_values(X_sample, nsamples=200)
            if isinstance(shap_values, list):
                shap_values = shap_values[1]

        self.shap_values = shap_values
        self.shap_features = feature_names
        self.shap_sample = X_sample

        # Bar plot
        shap.summary_plot(shap_values, X_sample,
                          feature_names=feature_names, plot_type='bar')

        # Beeswarm plot
        shap.summary_plot(shap_values, X_sample, feature_names=feature_names)

    def plot_shap_dependence(self, feature_name = None, interaction_index = 'auto'):
        '''
        SHAP dependence plot for the top feature (or a named one).
        feature_name: str name of feature
        interaction_index: str or int index of interaction
        '''

        if not hasattr(self, 'shap_values'):
            raise RuntimeError('Run plot_shap_analysis() first.')

        # Specified feature or take the top feature
        if feature_name is None:
            top_idx = int(np.argmax(np.abs(self.shap_values).mean(axis=0)))
            feature_name = self.shap_features[top_idx]

        shap.dependence_plot(
            feature_name, self.shap_values, self.shap_sample,
            feature_names = self.shap_features,
            interaction_index = interaction_index, show = True
        )

