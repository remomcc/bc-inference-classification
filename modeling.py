class PreprocessingPipeline:
    '''
    Thin wrapper around a sklearn Pipeline that handles three optional steps:
        transform → SafeTransformer (log-transform skewed features)
        scale → DataFrameScaler (StandardScaler preserving column names)
        vif → VIFSelector (iterative VIF-based feature removal)

    Used by both the inference path (LogisticInferencePipeline) and the
    classification path (PipelineBuilder).

    When all intent flags are False, the pipeline will passthrough.
    '''

    def __init__(self, intent = None, feature_transforms = None, vif_thresh = 5.0):
        '''
        intent: dict with keys 'transform', 'scale', 'vif'.
                Each value is bool. Missing keys are treated as False.
        feature_transforms : dict or None
            Mapping {feature_name: 'log'|'raw'}.  If None, SafeTransformer
            auto-detects skewed features (skew > 1 → 'log').
        vif_thresh : float of VIF threshold for feature removal.
        '''

        self.intent = intent or {}
        self.feature_transforms = feature_transforms
        self.vif_thresh = vif_thresh

        # Extract steps
        steps = []
        if self.intent.get('transform'):
            steps.append(('transform', SafeTransformer(feature_transforms)))
        if self.intent.get('scale'):
            steps.append(('scaler', DataFrameScaler()))
        if self.intent.get('vif'):
            steps.append(('vif', VIFSelector(thresh=vif_thresh)))

        # An empty Pipeline (no steps) is a valid passthrough in sklearn.
        self._pipeline = Pipeline(steps) if steps else None

        self.feature_metadata = {}
        self.feature_cols = None

    def fit_transform(self, X, y = None):
        '''
        Fit and transform the data.
        X: DataFrame of features
        y: series of labels
        '''

        if self._pipeline is None:
            self._store_metadata(X)
            return X.copy()

        # Retrieve transformation str of features if there is a pipeline
        X_proc = self._pipeline.fit_transform(X, y)
        self._store_metadata(X_proc)

        return X_proc

    def fit(self, X, y = None):
        '''
        Fit the pipeline. Can change later to just fit instead of fit_transform.
        X: DataFrame of features
        y: series of labels
        '''

        if self._pipeline is None:
            return self

        # Fit and transform data via model pipeline with steps
        self.fit_transform(X, y)
        return self

    def transform(self, X):
        '''
        Transform the data.
        X: DataFrame of features
        '''
        if self._pipeline is None:
            return X.copy()

        # Transform data via model pipeline with steps
        return self._pipeline.transform(X)

    def _store_metadata(self, X_proc):
        '''
        Store feature metadata and feature names.
        X_proc: DataFrame of processed features.
        '''

        # Get feature metadata when transform = True
        transformer = (self._pipeline.named_steps.get('transform')
                       if self._pipeline else None)

        if transformer and hasattr(transformer, 'get_feature_metadata'):
            raw = transformer.get_feature_metadata()
            self.feature_metadata = {
                f: (meta.get('transformation', 'raw')
                    if isinstance(meta, dict) else meta)
                for f, meta in raw.items()
            }
        else:
            # No transformations required for tree-based models
            self.feature_metadata = {col: 'raw' for col in X_proc.columns}

        self.feature_cols = list(X_proc.columns)

    def get_feature_metadata(self):
        '''
        Return feature metadata.
        '''
        return self.feature_metadata

    def get_feature_names_out(self):
        '''
        Return feature names.
        '''
        return self.feature_cols

