def compute_ece(y_true, y_prob, n_bins = 10):
    '''
    Calculate the expected calibration error.
    y_true: series of true binary labels
    y_prob: series of predicted probabilities
    n_bins: number of calibration bins
    '''

    # Bins
    bins = np.linspace(0, 1, n_bins + 1)
    bin_ids = np.clip(np.digitize(y_prob, bins) - 1, 0, n_bins - 1)
    counts = np.bincount(bin_ids, minlength = n_bins)
    nonzero = counts > 0

    # Predictions sum and mean
    pred_sum = np.bincount(bin_ids, weights = y_prob, minlength = n_bins)
    pred_mean = np.zeros(n_bins)
    pred_mean[nonzero] = pred_sum[nonzero] / counts[nonzero]

    # Actual sum and mean
    acc_sum = np.bincount(bin_ids, weights = y_true, minlength = n_bins)
    acc_mean = np.zeros(n_bins)
    acc_mean[nonzero] = acc_sum[nonzero] / counts[nonzero]

    return float(np.sum((counts[nonzero] / len(y_prob))
                        * np.abs(pred_mean[nonzero] - acc_mean[nonzero])))


def get_probabilities(pipe, X):
    '''
    Return (target's positive probability, target's negative probability,
    target's probability matrix) from any pipeline.
    Works for predict_proba and decision_function models.
    pipe: sklearn.pipeline.Pipeline
    X: DataFrame of features
    '''

    # Model
    model = pipe.named_steps['model']

    # Transformations are only for linear or distance-based models
    X_model = pipe[:-1].transform(X) if len(pipe.steps) > 1 else X

    # Models with predict_proba
    if hasattr(model, 'predict_proba'):
        probs = model.predict_proba(X_model)
        if probs.shape[1] == 2:
            return probs[:, 1], probs[:, 0], probs
        y_pos = probs.flatten()
        return y_pos, 1 - y_pos, np.column_stack([1 - y_pos, y_pos])

    # If it does not have predict_proba, calculate probability by scaling scores from decision function
    scores = model.decision_function(X_model).reshape(-1, 1)
    y_pos  = MinMaxScaler().fit_transform(scores).flatten()

    return y_pos, 1 - y_pos, np.column_stack([1 - y_pos, y_pos])


def run_baseline(X_train, y_train, X_test, y_test, strategy = 'stratified'):
    '''
    Fit a DummyClassifier and return metric dict.
    X_train: DataFrame of training features
    y_train: series of training labels
    X_test: DataFrame of test features
    y_test: series of test labels
    strategy: str for strategy. Options: 'stratified', 'most_frequent', 'prior', 'uniform', 'constant'
    '''

    # Instatiate and fit classifier
    clf = DummyClassifier(strategy = strategy, random_state = 42)
    clf.fit(X_train, y_train)

    # Classifier predictions and probabilities
    y_pred = clf.predict(X_test)
    y_prob_matrix = clf.predict_proba(X_test)
    y_prob = y_prob_matrix[:, 1]

    return {
        'model': f'Baseline ({strategy})',
        'accuracy': accuracy_score(y_test, y_pred),
        'precision': precision_score(y_test, y_pred, pos_label=1, zero_division=0),
        'recall': recall_score(y_test, y_pred, pos_label=1),
        'f1': f1_score(y_test, y_pred, pos_label=1, zero_division=0),
        'f2': fbeta_score(y_test, y_pred, beta=2, average = 'binary'),
        'pr_auc': average_precision_score(y_test, y_prob),
        'roc_auc': roc_auc_score(y_test, y_prob),
        'brier_score': brier_score_loss(y_test, y_prob, pos_label=1),
        'log_loss': log_loss(y_test, y_prob_matrix),
        'ece': compute_ece(y_test.values, y_prob),
    }

