    def plot_error_distributions(self, features = None, max_features = 20):
        '''
        KDE plots: correct vs incorrect predictions for each feature.
        features: list of feature names
        max_features: int maximum number of features to plot
        '''

        df = self.error_analysis.get('full_table') if self.error_analysis else None

        if df is None:
            raise RuntimeError('Run analyze_errors() first.')

        if features is None:

            # Get feature processing table
            ft = self.analyzer.feature_processing_table_

            if ft is None:
                raise RuntimeError('Build feature_processing_table first.')

            name = self.analyzer.best_model_name

            # Select features from the model but not the intercept
            features = (
                ft.query('model == @name and feature != "__intercept__"')
                .assign(score = lambda d: d.get(
                    'importance',
                    d.get('coefficient',
                    d.get('permutation_importance',
                          pd.Series(0, index=d.index)))))
                .sort_values('score', ascending=False)
                .head(max_features)['feature'].tolist()
            )

        n = len(features)
        fig, axes = plt.subplots((n + 1) // 2, 2,
                                  figsize=(12, 4 * ((n + 1) // 2)))
        axes = axes.flatten()

        for ax, f in zip(axes, features):
            correct = df.loc[~df['is_error'], f]
            incorrect = df.loc[df['is_error'],  f]
            if len(correct) > 1:
                sns.kdeplot(correct, label='Correct', fill = True, ax = ax)

            if len(incorrect) >= 1:
                if len(incorrect) > 1:
                    sns.kdeplot(
                        incorrect,
                        label='Incorrect',
                        fill=True,
                        ax=ax)

                # For single error, draw a line on plot
                else:
                    ax.axvline(
                        incorrect.iloc[0],
                        color='red',
                        linestyle='--',
                        label='Incorrect')

            ax.set_title(f'{f} — Correct vs Incorrect')
            ax.legend()

        for ax in axes[n:]:
            ax.axis('off')

        plt.tight_layout()
        plt.show()

