class BaseInferenceModel(ABC):
    '''
    Abstract base for a fitted logistic inference model.
    Subclasses implement fit() and expose coef_, pvalues_, se_, conf_int_.
    '''

    def __init__(self, coef_warn_thresh = 20):
        '''
        coef_warn_thresh : float threshold and warn if any coefficient exceeds this after fitting.
        '''

        self.coef_warn_thresh = coef_warn_thresh

    def _check_model_stability(self):
        '''
        Warn if coefficients are greater than threshold after fitting likely
        due to quasi-separation.
        '''

        coefs = self.coef_.drop('const', errors = 'ignore')
        if np.any(np.abs(coefs) > self.coef_warn_thresh):
            warnings.warn(
                f'Large coefficients detected (>|{self.coef_warn_thresh}|). '
                'Likely quasi-separation.',
                RuntimeWarning
            )

    @abstractmethod
    def fit(self, X, y): ...

    def get_coef(self): return self.coef_
    def get_pvalues(self): return self.pvalues_
    def get_se(self): return self.se_
    def get_conf_int(self): return self.conf_int_
    def get_feature_names(self): return self.coef_.index

class FirthLogisticModel(BaseInferenceModel):
    '''
    Firth's logistic regression via firthmodels.FirthLogisticRegression

    Use when standard MLE diverges due to quasi-complete separation.
    Inference uses the likelihood-ratio test (LRT) by default.
    Profile-likelihood CIs are used for the confidence intervals.
    '''

    def __init__(self, coef_warn_thresh = 20, inference_method = 'lrt', ci_method = 'pl'):
        '''
        coef_warn_thresh: float threshold to warn if any coefficient exceeds this value after fitting
        inference_method: 'lrt' | 'wald' to compute SE and p-values
        ci_method: 'pl' | 'wald' for confidence interval method
        '''

        super().__init__(coef_warn_thresh)
        self.inference_method = inference_method
        self.ci_method = ci_method

    def _check_full_rank(self, X, tol = 1e-10):
        '''
        Check that design matrix is full rank.
        X: DataFrame of features
        tol: float tolerance for singular values
        '''

        _, s, _ = np.linalg.svd(X, full_matrices = False)
        if np.sum(s > tol) < X.shape[1]:
            raise ValueError('Design matrix is rank deficient. Firth requires full rank.')

    def fit(self, X, y):
        '''
        X: DataFrame where features are already preprocessed (transformed, scaled, VIF-filtered)
        y: Series of target labels
        '''

        # Check if design matrix is full rank
        self._check_full_rank(X)

        # Instantiate Firth logistic regression model
        self.model_ = (FirthLogisticRegression(
            max_iter = 1000, max_halfstep = 50, gtol = 1e-3, xtol = 1e-3
            ).fit(X.values, y.values)
            )

        # Coefficients with features first and then intercept
        index = list(X.columns) + ['const']
        coef = np.concatenate([self.model_.coef_.ravel(), [self.model_.intercept_]])
        self.coef_ = pd.Series(coef, index = index)

        # SE and p-values based on inference method
        # penalized maximum likelihood estimation (lrt) or otherwise
        if self.inference_method == 'lrt':
            self.model_.lrt()
            self.se_ = pd.Series(self.model_.lrt_bse_, index = index)
            self.pvalues_ = pd.Series(self.model_.lrt_pvalues_, index = index)
        else:
            self.se_ = pd.Series(self.model_.bse_, index = index)
            self.pvalues_ = pd.Series(self.model_.pvalues_, index = index)

        # Confidence intervals
        ci = self.model_.conf_int(method = self.ci_method)
        self.conf_int_ = pd.DataFrame(
            {'lower': ci[:, 0], 'upper': ci[:, 1]}, index=index
        )

        # Flag features where PL-CI failed
          #lower >= upper indicates optimizer hit its iteration cap which is a characteristic of quasi-separation).
        # These features get NaN OR CIs in the table rather than a misleading zero-width interval.
        self.ci_valid_ = self.conf_int_['lower'] < self.conf_int_['upper']

        # Warn when features have non-valid confidence intervals
        bad = list(self.ci_valid_.index[~self.ci_valid_])
        if bad:
            warnings.warn(
                f'Profile-likelihood CI failed for: {bad}. '
                'CI bounds are equal; quasi-separation likely. '
                'These features are flagged unstable_ci = True in the table.',
                RuntimeWarning
            )

        # Check if coefficients are greater than coefficient threshold
          # if greater than threshold, likely quasi-separation
        self._check_model_stability()

        return self

class MLELogisticModel(BaseInferenceModel):
    '''
    Standard MLE logistic regression via statsmodels.
    Use when separation is not a concern.
    '''

    def fit(self, X, y):
        '''
        X: DataFrame where features are already preprocessed (transformed, scaled, VIF-filtered)
        y: Series of target labels
        '''

        # Add constant and fit logistic regression model
        X_sm = sm.add_constant(X)
        result = sm.Logit(y, X_sm).fit(disp=0)

        # Save model coefficients, standard error, p-values, and confidence interval
        self.coef_ = result.params
        self.se_  = result.bse
        self.pvalues_ = result.pvalues
        ci = result.conf_int()
        ci.columns = ['lower', 'upper']
        self.conf_int_ = ci


        # Check if coefficients are greater than coefficient threshold
          # if greater than threshold, likely quasi-separation
        self._check_model_stability()

        return self

