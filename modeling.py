class LogisticInferencePipeline:
    '''
    Combine the PreprocessingPipeline with a BaseInferenceModel estimator.

    -Preprocessing is delegated to PreprocessingPipeline, which handles the passthrough case when intent is empty or None.
    -The estimator (FirthLogisticModel / MLELogisticModel) receives the processed DataFrame.
    -After fitting, .get_result() returns an InferenceResult for tabulation and plotting.
    '''

    def __init__(self, estimator, intent = None, feature_transforms = None,
                 vif_thresh = 5.0):
        '''
        estimator: BaseInferenceModel instance (e.g. FirthLogisticModel() or MLELogisticModel())
        intent: dict or None (e.g. {'transform': True, 'scale': True, 'vif': True})
                Pass None or an empty dict for no preprocessing.
        feature_transforms: dict or None
                optional override for per-feature transform names.
        vif_thresh: float for VIF threshold forwarded to PreprocessingPipeline.
        '''

        self.estimator = estimator

        # Instantiate preprocessor
        self.preprocessor = PreprocessingPipeline(
            intent = intent or {},
            feature_transforms = feature_transforms,
            vif_thresh = vif_thresh
        )

        self.feature_metadata = {}
        self.feature_cols = None

    def fit(self, X, y):
        '''
        Fit the pipeline.
        X: DataFrame of features
        y: series of labels
        '''

        # Fit and transform data in preprocessing pipeline
        X_proc = self.preprocessor.fit_transform(X, y)
        self.feature_metadata = self.preprocessor.get_feature_metadata()
        self.feature_cols = self.preprocessor.get_feature_names_out()

        # Convert to DataFrame if VIFSelector returned a plain array
        if not isinstance(X_proc, pd.DataFrame):
            X_proc = pd.DataFrame(X_proc, columns = self.feature_cols,
                                  index = X.index[:len(X_proc)])

        # Fit data post-preprocessing into estimator
        self.estimator.fit(X_proc, y)

        return self

    def get_coef(self):
        '''
        Return fitted coefficients.
        '''
        return self.estimator.get_coef()

    def get_pvalues(self):
        '''
        Return fitted p-values.
        '''
        return self.estimator.get_pvalues()

    def get_se(self):
        '''
        Return fitted standard errors.
        '''
        return self.estimator.get_se()

    def get_conf_int(self):
        '''
        Return fitted confidence intervals.
        '''
        return self.estimator.get_conf_int()

    def get_result(self):
        '''
        Return an InferenceResult ready for .to_table()- create table and
        .plot_forest()- create forest plot.
        '''
        return InferenceResult(
            coef = self.estimator.get_coef(),
            se = self.estimator.get_se(),
            pvalues = self.estimator.get_pvalues(),
            conf_int = self.estimator.get_conf_int(),
            feature_metadata = self.feature_metadata,
        )

class InferenceResult:
    '''
    Hold fitted inference outputs and provide tabulation + plotting.

    All odds ratios (ORs) are per one standard deviation increase in the preprocessed
    feature (log-transformed where applicable, then standardized).
    '''

    def __init__(self, coef, se, pvalues, conf_int, feature_metadata):
        '''
        coef: series of fitted coefficients
        se: series of fitted standard errors
        pvalues: series of fitted p-values
        conf_int: DataFrame of fitted confidence intervals
        '''
        self.coef = coef
        self.se = se
        self.pvalues = pvalues
        self.conf_int = conf_int
        self.feature_metadata = feature_metadata

    def to_table(self):
        '''
        Build inference table (features only, sorted by p-value)

        unstable_ci: True means that the profile-likelihood CI optimizer did not
        converge for that feature (lower == upper or OR is not within the confidence interval).
        OR CI columns are NaN for these rows.
        Interpret the feature's direction (OR > 1 or < 1) but do not report the CI as a reliable interval.
        '''

        feats = [f for f in self.coef.index if f != 'const']
        coef = self.coef[feats]
        se = self.se[feats]
        pval = self.pvalues[feats]
        ci_lo = self.conf_int.loc[feats, 'lower']
        ci_hi = self.conf_int.loc[feats, 'upper']

        # Detect invalid CIs (lower >= upper)
        ci_valid = (
            (ci_lo.values < ci_hi.values) &
            (coef.values >= ci_lo.values) &
            (coef.values <= ci_hi.values)
        )

        # Inference table
        table = (pd.DataFrame({
            'feature': feats,
            'transformation': [self.feature_metadata.get(f, 'raw') for f in feats],
            'coefficient': coef.values,
            'std_error': se.values,
            'z_value': (coef / se).values,
            'p_value': pval.values,
            'OR_per_SD': np.exp(coef.values),

            # Set OR CI to NaN where PL-CI failed so the forest plot does not draw a zero-width error bar
            'ci_lower_OR': np.where(ci_valid, np.exp(ci_lo.values), np.nan),
            'ci_upper_OR': np.where(ci_valid, np.exp(ci_hi.values), np.nan),
            'unstable_ci': ~ci_valid,
        })
        .sort_values('p_value')
        .reset_index(drop=True))

        return table

    def plot_forest(
        self,
        data,
        primary = 'OR_bootstrap',
        primary_lower = 'ci_lower_bootstrap',
        primary_upper = 'ci_upper_bootstrap',
        secondary = 'OR_per_SD',
        secondary_lower = 'ci_lower_OR',
        secondary_upper = 'ci_upper_OR',
        clip_ci = (1e-5, 1e5),
        bootstrap_thresh = 0.8,
        show_significance = True
    ):
        '''
        Forest plot with bootstrap overlay and original-model reference.

        data: DataFrame output of BootstrapInference.build_forest_data().
              Must contain a 'feature' column plus the primary/secondary OR columns.
        primary/primary_lower/primary_upper: str of column with bootstrap OR point estimate and CI bounds.
        secondary/secondary_lower/secondary_upper: str of column with original model OR and CI bounds (plotted as a reference square).
        clip_ci : tuple of x-axis limits on log scale.
        bootstrap_thresh : float threshold for marking a feature as robust (green vs. grey dot).
        show_significance : bool where True values are overlayed with a red circle for p_value < 0.05.
        '''

        data = data.copy().iloc[::-1]   # bottom-to-top ordering

        x_vals = data[primary]
        x_lo = data[primary_lower]
        x_hi = data[primary_upper]
        xerr = [np.maximum(x_vals - x_lo, 0),
                np.maximum(x_hi - x_vals, 0)]

        # Check if CI intervals are ordered correctly
        if (x_vals - x_lo < 0).any() or (x_hi - x_vals < 0).any():
            logging.warning('Some CI bounds inverted. Check bootstrap scaling.')

        fig, ax = plt.subplots(figsize=(9, max(6, len(data) * 0.55)))

        # Primary: bootstrap OR
        ax.errorbar(x_vals, data['feature'], xerr = xerr,
                    fmt = 'o', color = 'black', ecolor = 'gray',
                    capsize = 3, label = 'Bootstrap OR', zorder = 3)

        # Secondary: original model OR
        if secondary in data.columns:
            ref_vals = data[secondary]
            ref_lo = data.get(secondary_lower, ref_vals)
            ref_hi = data.get(secondary_upper, ref_vals)
            ref_err = [np.maximum(ref_vals - ref_lo, 0),
                        np.maximum(ref_hi - ref_vals, 0)]
            ax.errorbar(ref_vals, data['feature'], xerr = ref_err,
                        fmt = 's', color = 'blue', ecolor = 'lightblue',
                        capsize = 3, label = 'Original model OR', zorder = 2)

        # Significance overlay
        if show_significance and 'p_value' in data.columns:
            sig = data['p_value'] < 0.05
            ax.scatter(x_vals[sig], data.loc[sig, 'feature'],
                       color = 'red', s = 60, label = 'p < 0.05', zorder = 4)

        # Bootstrap stability overlay
        if 'selection_frequency' in data.columns:
            robust = data['selection_frequency'] >= bootstrap_thresh
            colors = robust.map({True: 'green', False: 'gray'})
            sizes = 50 + 100 * data['selection_frequency']
            ax.scatter(x_vals, data['feature'],
                       color = colors, s = sizes, alpha = 0.6,
                       label = 'Bootstrap stability', zorder = 5)

        # Off-scale annotations
        off = (x_vals < clip_ci[0]) | (x_vals > clip_ci[1])
        for feat, val in zip(data.loc[off, 'feature'], x_vals[off]):
            x_a = clip_ci[1] * 0.95 if val > clip_ci[1] else clip_ci[0] * 1.05
            ha  = 'right' if val > clip_ci[1] else 'left'
            ax.annotate('Off-scale', xy = (x_a, feat), xytext = (0, 6),
                        textcoords = 'offset points', va = 'bottom', ha = ha,
                        fontsize = 8, color = 'dimgray')

        ax.axvline(1, linestyle='--', color='blue', zorder=1)
        ax.set_xscale('log')
        ax.set_xlim(*clip_ci)
        ax.set_xlabel('Odds Ratio per SD (log scale)')
        ax.set_ylabel('Feature')
        ax.set_title('Forest Plot (Firth) with Bootstrap Stability')
        ax.legend()
        plt.tight_layout()
        plt.show()

"""### Bootstrap Inference"""

class BootstrapInference:
    '''
    Bootstrap resampling over the full LogisticInferencePipeline.

    Each resample independently re-fits the preprocessor (transform, scale,
    VIF) and the estimator, so the resulting ORs reflect the combined
    uncertainty of preprocessing decisions and model estimation.

    Store exp(β)- the OR per SD- directly and compute means and
    quantile CIs on the OR scale.

    Selection frequency = fraction of resamples where a feature survived
    VIF AND had p < alpha.  Features not retained after VIF will not
    appear in the summary (NaN).
    '''

    def __init__(self, base_model, n_bootstrap = 500,
                 bootstrap_thresh = 0.8, random_state = 42):
        '''
        base_model: LogisticInferencePipeline,
                    fitted pipeline whose deepcopy is re-fitted on each resample
        n_bootstrap: int number of bootstrap resamples
        bootstrap_thresh: float for selection-frequency threshold for the 'robust' flag
        random_state: float for reproducibility
        '''
        self.base_model = base_model
        self.n_bootstrap = n_bootstrap
        self.bootstrap_thresh = bootstrap_thresh
        self.random_state = random_state

        # In-memory state
        self._bootstrap_ors = []
        self._bootstrap_pvals = []
        self._n_successful = 0

    def fit(self, X, y):
        '''
        Fit the pipeline for bootstrapping.
        X: DataFrame of features
        y: series of labels
        '''
        rng = np.random.default_rng(self.random_state)
        n = len(X)

        # Initialize list of present features
        self._feature_presence = []

        # Run bootstrapping
        for _ in range(self.n_bootstrap):
            idx  = rng.integers(0, n, n)
            X_rs = X.iloc[idx].reset_index(drop=True)
            y_rs = y.iloc[idx].reset_index(drop=True)

            model = deepcopy(self.base_model)
            try:
                model.fit(X_rs, y_rs)
                coef = model.get_coef().drop('const', errors = 'ignore')
                pval = model.get_pvalues().drop('const', errors = 'ignore')
                self._bootstrap_ors.append(np.exp(coef))
                self._bootstrap_pvals.append(pval)
                self._n_successful += 1
                present = coef.index
                presence_vec = pd.Series(1, index = present)
                self._feature_presence.append(presence_vec)
            except Exception:
                continue

        if self._n_successful == 0:
            raise RuntimeError('All bootstrap iterations failed. '
                               'Check for separation or rank deficiency.')

        # Save bootstrap ORs, p-values, presence
        self._or_df = pd.DataFrame(self._bootstrap_ors)
        self._pval_df = pd.DataFrame(self._bootstrap_pvals)
        self._presence_df = (
            pd.DataFrame(self._feature_presence)
            .reindex(columns = self._or_df.columns)
            .fillna(0)
        )

        return self

    def get_or_summary(self):
        '''
        Point estimates and quantile CIs for bootstrap ORs.
        '''

        s = pd.DataFrame(index = self._or_df.columns)

        or_df_clipped = self._or_df.clip(lower = 1e-10, upper = 1e10)
        log_or_df = np.log(or_df_clipped)

        # Mean on log scale
        s['OR_bootstrap'] = np.exp(log_or_df.mean())

        # CI on log scale
        s['ci_lower_bootstrap'] = np.exp(
            log_or_df.quantile(0.025)
        )
        s['ci_upper_bootstrap'] = np.exp(
            log_or_df.quantile(0.975)
        )

        # Sign consistency where feature exists
        sign = (log_or_df > 0).astype(float)
        sign_consistency = sign.sum() / self._presence_df.sum()
        s['sign_consistency'] = np.maximum(sign_consistency, 1 - sign_consistency)

        return s.sort_values('OR_bootstrap', ascending = False)

    def get_stability_selection(self, alpha=0.05):
        '''
        Fraction of resamples where feature was retained AND significant.
        alpha: float for p-value threshold
        '''

        significant = (self._pval_df < alpha).astype(float)

        # Frequency of significance when present in resample
        freq = significant.sum() / self._presence_df.sum()

        return (pd.DataFrame({'selection_frequency': freq})
                  .sort_values('selection_frequency', ascending = False)
               )

    def get_final_inference(self):
        '''
        Combined OR summary, selection, stability, and robust flag.
        '''

        # Bootstrap OR summary
        summary = self.get_or_summary()

        # Stability
        stability = self.get_stability_selection()

        # Final inference dataframe
        final = summary.join(stability, how = 'outer')
        final['robust'] = (
            (final['selection_frequency'] >= self.bootstrap_thresh) &
            (final['sign_consistency'] >= 0.9)
        )
        final['stability_score'] = final['selection_frequency'] * final['sign_consistency']

        return final.sort_values('stability_score', ascending=False)

    def build_forest_data(self, base_inference_table):
        '''
        Merge bootstrap summary with the base model's inference table.
        The result is passed directly to InferenceResult.plot_forest().

        base_inference_table: DataFrame the output of InferenceResult.to_table().
        '''

        # Retrieve final bootstrap inference dataframe
        summary = self.get_final_inference()

        # Reset index to feature
        summary = (summary.reset_index()
                          .rename(columns = {'index': 'feature'})
        )

        # Merge on feature
        merged = summary.merge(base_inference_table, on = 'feature', how = 'left')

        return merged

    def plot_selection_frequency(self, top_n = None, figsize = (8, 6)):
        '''
        Bar chart of bootstrap selection frequency with threshold line.
        top_n: int for top n features to plot
        '''

        # Reset stability selection dataframe
        df = (self.get_stability_selection()
              .reset_index()
              .rename(columns = {'index': 'feature'}))

        # Plot only top n features
        if top_n:
            df = df.head(top_n)

        plt.figure(figsize = figsize)
        sns.barplot(data = df, y = 'feature', x = 'selection_frequency',
                    palette = 'viridis', hue = 'feature', legend = False)
        plt.axvline(self.bootstrap_thresh, linestyle = '--', color = 'red',
                    label = f'robust ≥ {self.bootstrap_thresh}')

        plt.title('Bootstrap Feature Stability')
        plt.xlabel('Selection Frequency')
        plt.ylabel('Feature')
        plt.legend()
        plt.tight_layout()
        plt.show()

